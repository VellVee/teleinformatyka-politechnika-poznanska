	LJMP	START
	ORG	100H
START:
	SETB RS0
	SETB RS1
	MOV A,#0
	LCALL LCD_CLR 		
	LCALL WAIT_KEY  	
	PUSH ACC
	LCALL TO_BCD 		
	LCALL WRITE_HEX 	
	LCALL WAIT_KEY  	
	PUSH ACC
	LCALL TO_BCD 		
	LCALL WRITE_HEX 	
	LCALL WAIT_KEY		
	PUSH ACC
	
	CJNE A,#10,ODEJM 	
	MOV ACC, #'+'
	LCALL WRITE_DATA
	MOV ACC, #'='
	LCALL WRITE_DATA
	POP ACC				
	POP ACC				
	MOV R0, A			
	POP ACC				
	ADD A, R0			
	LCALL TO_BCD 		
	LCALL WRITE_HEX 	
	LJMP STOP	
	
ODEJM:
	CJNE A,#11,MNOZ		
	MOV ACC, #'-'
	LCALL WRITE_DATA
	MOV ACC, #'='
	LCALL WRITE_DATA
	POP ACC				
	POP ACC
	MOV R0, A
	POP ACC
	CLR C
	SUBB A, R0			
	LCALL TO_BCD 		
	LCALL WRITE_HEX 	
	LJMP STOP
	
DZIEL:
	CJNE A,#13,START	
	MOV ACC, #'/'		
	LCALL WRITE_DATA
	MOV ACC, #'='		
	LCALL WRITE_DATA
	POP ACC				
	POP ACC				
	MOV R2,A           
	MOV B,A
	POP ACC				
	DIV AB
	MOV R3,B			
	LCALL TO_BCD
	LCALL WRITE_HEX     
	CJNE R3,#0,RESZTA	 
	LJMP STOP			

RESZTA:					
	MOV A,#' '
	LCALL WRITE_DATA
	MOV A,R3			
	LCALL TO_BCD
	LCALL WRITE_HEX		
	MOV A,#'/'
	LCALL WRITE_DATA
	MOV A,R2			
	LCALL TO_BCD
	LCALL WRITE_HEX
	LJMP STOP
	
MNOZ:
	CJNE A,#12,DZIEL	
	MOV ACC, #'*'
	LCALL WRITE_DATA
	MOV ACC, #'='
	LCALL WRITE_DATA
	POP ACC				
	POP ACC				
	MOV B, A
	POP ACC
	MUL AB
	MOV R0, B
	MOV R1, A
	MOV A, R0
	LCALL WRITE_HEX 	
	MOV A, R1
	LCALL WRITE_HEX 	
	LJMP STOP
	
TO_BCD: 				
	MOV B,#10			
	DIV AB				
	SWAP A				
	ORL A,B				
	RET
	NOP
	
STOP:					
	LCALL WAIT_KEY
	LJMP	START	
	NOP

