	LJMP START
	ORG 100H
START:
	LCALL LCD_CLR
	LCALL WAIT_KEY
	MOV R1, A
	LCALL KONWERTUJ
	LCALL WRITE_HEX
	LCALL WAIT_KEY
	MOV R0, A
	MOV A, R1
	SJMP DODAJ
	
DODAJ:
	ADD A, R0
	MOV R0, A
	LCALL KONWERTUJ
	LCALL LCD_CLR
	MOV A, R3
	LCALL WRITE_HEX
	LCALL WAIT_KEY
	SJMP DODAJ
	
KONWERTUJ:
	MOV B, #10
	DIV AB;
	SWAP A
	ADD A, B
	MOV R3, A
	RET
	