	MOV DPTR, #F_CSDS
	
	MOV A,#DISPLAY
	MOVX @DPTR, A
	
	MOV DPTR,#F_CSDB
	
	MOV  A,#COD_P
	MOVX @DPTR,A
	
	CLR SEG_ON
	
	SJMP $