SEG_ON EQU P1.6
F_CSDS EQU 0FF30H
F_CSDB EQU 0FF38H

DISPLAY EQU 00011111B

COD_P	EQU 01110011B
COD_A	EQU 01110111B
COD_W	EQU 00011100B
COD_E	EQU 01111001B
COD_L	EQU 00111000B

	LJMP START
	ORG 100H

