SEG_ON EQU P1.6 
F_CSDS EQU 0FF30H ;
F_CSDB EQU 0FF38H ;
DISPLAY6 EQU 00000001B
DISPLAY5 EQU 00000010B
DISPLAY4 EQU 00000100B
DISPLAY3 EQU 00001000B
DISPLAY2 EQU 00010000B
DISPLAY1 EQU 00100000B

COD5 EQU 00111000B;L
COD4 EQU 01111001B;E
COD3 EQU 00111110B;W
COD2 EQU 01110111B;A
COD1 EQU 01110011B;P

DELAY EQU 255

	LJMP START
	ORG 100H
START:
	;1
	MOV DPTR,#F_CSDS
	MOV A,#DISPLAY1
	MOVX @DPTR,A
	
	MOV DPTR,#F_CSDB
	MOV A,#COD1
	MOVX @DPTR,A
	
	CLR SEG_ON
	MOV A, #DELAY
	LCALL DELAY_MS
	
	;2
	MOV DPTR,#F_CSDS
	MOV A,#DISPLAY2
	MOVX @DPTR,A
	
	MOV DPTR,#F_CSDB
	MOV A,#COD2
	MOVX @DPTR,A
	
	CLR SEG_ON
	MOV A, #DELAY
	LCALL DELAY_MS
	
	;3
	MOV DPTR,#F_CSDS
	MOV A,#DISPLAY3
	MOVX @DPTR,A
	
	MOV DPTR,#F_CSDB
	MOV A,#COD3
	MOVX @DPTR,A
	
	CLR SEG_ON
	MOV A, #DELAY
	LCALL DELAY_MS
	
	;4
	MOV DPTR,#F_CSDS
	MOV A,#DISPLAY4
	MOVX @DPTR,A
	
	MOV DPTR,#F_CSDB
	MOV A,#COD4
	MOVX @DPTR,A
	
	CLR SEG_ON
	MOV A, #DELAY
	LCALL DELAY_MS
	
	;5
	MOV DPTR,#F_CSDS
	MOV A,#DISPLAY5
	MOVX @DPTR,A
	
	MOV DPTR,#F_CSDB
	MOV A,#COD5
	MOVX @DPTR,A
	
	CLR SEG_ON
	MOV A, #DELAY
	LCALL DELAY_MS
	
	SJMP START
	