DISPLAY EQU P1.7
PRZYCISK EQU 00000001B	

		LJMP 	START
		ORG 	100H
START:
		MOV		TMOD,#01110000B
		MOV		TL1,#0FCH
		MOV		TH1,#0FFH
		SETB	TR1
		
		MOV R0, #CSDS
		MOV A, #PRZYCISK
		MOVX @R0, A
		
WYSWIETL:
		LCALL LCD_CLR 
		MOV R1, TH1
		LCALL WRITE_HEX
		MOV A, TL1
		LCALL WRITE_HEX
		JNB TF1, LOOP
		CLR	TF1
		CPL DISPLAY
		
LOOP:		
		MOV		A,R1
		CJNE A, TL1, WYSWIETL
		SJMP LOOP
		NOP
		
LOOP1:
		JNB P3.5, LOOP1
		
SLEEP:
		JB P3.5, SLEEP
		MOV A, TL1
		CJNE A, #11111111B, L1
		MOV TH1, #0 
		
		MOV A, TH1
		CJNE A, #11111111B, L2
		MOV TH1, #0 
		
		SETB TF1
		LJMP WYSWIETL
		
L1:
	INC TH1
	LJMP WYSWIETL
	
L2:
	INC TL1
	LJMP WYSWIETL
	NOP
	
		
		