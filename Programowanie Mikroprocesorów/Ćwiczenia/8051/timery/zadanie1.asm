SEG_ON EQU P1.6 ;włączenie wyświetlacza 7-segm.
LED_ON EQU P1.7
;Pełne adresy urządzeń we/wy systemu DSM-51
DISPLAY1 EQU 00000001B
COD1 EQU 00000000B;

	LJMP START
	ORG 100H
START:
	MOV TMOD, #01000000B ;Timer 0 w tryb licznika w trybie 0
	MOV TL1, #0FCH
	MOV TH1, #0
	MOV R1, #0fffff
	SETB TR1
	
	MOV R0,#CSDS
	MOV A,#DISPLAY1
	MOVX @R0,A
	
	MOV R0,#CSDB
	MOV A,#COD1
	MOVX @R0,A
	
	LCALL LCD_CLR
	CLR SEG_ON

PETLA:
	JB TF1, OVERFLOW
	MOV A, R1
	CJNE A, TL1, DISPLAY
	MOV A, TL1
	SJMP PETLA
	
DISPLAY:
	LCALL LCD_CLR
	MOV R1, TL1
	MOV A, TH1
	LCALL WRITE_HEX
	MOV A, TL1
	LCALL WRITE_HEX
	SJMP PETLA
	
OVERFLOW:
	CLR TF1
	CPL LED_ON
	MOV TL1, #250
	MOV TH1, #255
	SJMP PETLA
	