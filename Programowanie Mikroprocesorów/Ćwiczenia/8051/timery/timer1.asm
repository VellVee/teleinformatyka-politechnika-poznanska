DISPLAY EQU P1.7
PRZYCISK EQU 00000001B 		

		LJMP 	START
		ORG 	100H
START:
		MOV		TMOD,#01010000B
		MOV		TL1,#0FCH
		MOV		TH1,#0FFH
		SETB	TR1
		
		MOV R0, #CSDS
		MOV A, #PRZYCISK
		MOVX @R0, A
		
WYSWIETL:
		LCALL LCD_CLR 
		MOV R1, TL1
		MOV A, TH1
		LCALL WRITE_HEX
		MOV A,R1
		LCALL WRITE_HEX
		JNB TF1, LOOP
		CLR	TF1
		CPL DISPLAY
		
LOOP:		
		MOV		A,R1
		LCALL	WRITE_HEX
		
		CJNE A, TL1, WYSWIETL
		SJMP LOOP
		NOP