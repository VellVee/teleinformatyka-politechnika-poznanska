;TIMER 0
T0_G	EQU	0	;GATE
T0_C	EQU	0	;COUNTER/-TIMER
T0_M	EQU	1	;MODE (0..3)
TIM0	EQU	T0_M+T0_C*4+T0_G*8
;TIMER 1
T1_G	EQU	0	;GATE
T1_C	EQU	0	;COUNTER/-TIMER
T1_M	EQU	0	;MODE (0..3)
TIM1	EQU	T1_M+T1_C*4+T1_G*8

TMOD_SET	EQU	TIM0+TIM1*16

TH0_SET		EQU	256-180		;92160
TL0_SET		EQU	0


	LJMP	START
	ORG	100H
START:
	MOV	R1,#10
	MOV	TMOD,#TMOD_SET		;Timer 0 liczy czas
	MOV	TH0,#TH0_SET		;Timer 0 na 50ms
	MOV	TL0,#TL0_SET
	SETB	TR0			;start Timera

DIODA:
	MOV	A,#10
	CPL P1.7
	LCALL	TIME_100
	DJNZ	R1,DIODA

TIME_100:
	MOV	R0,A
	
ILOSC:
	JNB	TF0,$			
	MOV	TH0,#TH0_SET
	JNB	TF0,$
	MOV	TH0,#TH0_SET		
	CLR	TF0			
	
	DJNZ	R0,ILOSC

	RET